package com.framer.sense.feature.camera.vlm.agent

/** 指令用于创作，不将请求中的动作描述冒充模型实际完成的动作或严格去重结果。 */
object GeneratedReferencePrompt {
    fun build(instruction: String, variation: Int): String {
        val direction = when (variation % 4) {
            0 -> "侧重自然克制的姿态、细腻视线和表情"
            1 -> "侧重舒展的手臂线条、身体朝向变化和故事感"
            2 -> "侧重转身或回望的瞬间，改变头部与身体的关系"
            else -> "探索与静态站姿有区别的自然动作，保持普通人容易模仿"
        }
        return """
            请以我上传的照片为基础，为照片中的人物创作一张能够在当前真实现场模仿拍摄的人像摄影参考图。
            目标是：通过人物姿势、表情、站位、景别和构图的设计，让照片具有自然、协调、有艺术性的摄影表现。

            保留照片中同一个人物的身份特征、脸型、发型、体型，以及原有服装、颜色、花纹和配饰。保持真实人体比例和自然皮肤质感。如果没有人像，则由你创造满足用户要求的人像。

            以原照片的环境为现场依据，保持主要背景结构、物体位置、透视关系、天气、时段和光线方向。人物只能使用现场可确认的地面、座位或支撑条件，不添加拍摄所需的新道具。如果没有可确认的支撑条件，请根据环境判断是否可以生成特写、半身人像或多半身人像。

            保持原拍摄视角和画幅比例，可以在原图范围内适度裁切、调整人物位置。不要扩展原图之外的环境。

            请根据人物、服装和环境设计协调的身体姿态、肩颈关系、手势、头部朝向、视线与表情。动作应舒展自然、重心合理、手指放松，普通人能够模仿。用户有要求时，以用户要求为准。

            人物动作与画面安排应有明确的摄影设计，而不仅是调色或美化。优先保证现场能够拍出相近效果，不依赖虚构光线、夸张透视、改变身材或大幅后期处理。
            最终输出一张完整、真实的人像摄影参考照片，画面中不添加文字说明、箭头、边框或拼图。

            补充要求：
            画面必须有明确的主要人物，不能用凳子、家具等物体代替人物，不把背景路人作为主角。原图没有主要人物时，应新增满足用户要求的人物。
            支撑条件无法确认或原图未拍到地面时，不强行生成全身或补出地面，不虚构地面、平台、座椅或支撑。
            使用 Seedream 原生图层输出：底图保留现场背景，将主要人物（含头发、服饰、飘带及原有手持物）作为完整透明图层，名称为 reference_person，描述实际人物内容；家具和背景路人保留在底图。人物图层应与完整构图中的人物保持相同的位置、姿势、表情和服饰，不单独重新设计人物。
            本次创意序号为 ${variation + 1}，变化参考为：$direction；仅在符合用户要求时采用，不以变化参考覆盖用户要求，不牺牲现场可拍性。

            用户要求：${instruction.trim().take(2000)}
        """.trimIndent()
    }
}
